#!/bin/sh
# Copy a finished LM run's generated outputs into docs/ and assemble docs/report_lm.md.
# Usage: scripts/publish_lm_report.sh [results/lm_main] [docs/lm_main]
# Nothing is typed: report_lm.md is the generated report.md, verdicts.md, discovery_lm.md and
# sensitivity_p0.md concatenated, with figure/table links rewritten to the copied folder.
set -eu
RUN=${1:-results/lm_main}
DEST=${2:-docs/lm_main}
for f in report/report.md report/verdicts.md report/discovery_lm.md report/sensitivity_p0.md; do
  [ -f "$RUN/$f" ] || { echo "missing $RUN/$f: run the report, verdicts, discovery and sensitivity stages" >&2; exit 2; }
done
rm -rf "$DEST"
mkdir -p "$DEST"
cp -R "$RUN/report" "$DEST/report"
for d in data base measure timing; do
  mkdir -p "$DEST/$d"
  find "$RUN/$d" -maxdepth 1 \( -name '*.json' -o -name '*.jsonl' \) ! -name 'problems.jsonl' -exec cp {} "$DEST/$d/" \;
done
cp "$RUN/data/problems.jsonl" "$DEST/data/"
for f in "$RUN"/train/*/seed*/training.json "$RUN"/train/*/seed*/timing.json; do
  [ -f "$f" ] || continue
  rel=${f#"$RUN"/}
  mkdir -p "$DEST/$(dirname "$rel")"
  cp "$f" "$DEST/$rel"
done
PY=${PYTHON:-python}
"$PY" scripts/rederive_lm_headlines.py "$RUN" > "$DEST/rederive_headlines.txt"
REL=$(basename "$DEST")
OUT=docs/report_lm.md
{
  echo "<!-- generated by scripts/publish_lm_report.sh from $RUN; do not edit by hand -->"
  for f in report verdicts discovery_lm sensitivity_p0; do
    sed -e "s#(figures/#($REL/report/figures/#g" -e "s#\`tables/#\`$REL/report/tables/#g" "$RUN/report/$f.md"
    echo
  done
} > "$OUT"
echo "wrote $DEST and $OUT"
