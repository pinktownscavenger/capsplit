#!/bin/sh
# Copy the tail layer's generated outputs into docs/lm_main/tail/ and assemble its report.
# Usage: scripts/publish_lm_tail.sh [results/lm_main_tail] [docs/lm_main/tail]
# Nothing is typed: report.md = the hand-written plain-words answer (answer.md, no numbers) followed by
# the generated report. preregistration_tail.md and answer.md in DEST are never touched.
set -eu
RUN=${1:-results/lm_main_tail}
DEST=${2:-docs/lm_main/tail}
[ -f "$RUN/report/report.md" ] || { echo "missing $RUN/report/report.md: run the tail and tail-report stages" >&2; exit 2; }
mkdir -p "$DEST"
rm -rf "$DEST/tables" "$DEST/figures" "$DEST/timing"
cp -R "$RUN/report/tables" "$DEST/tables"
cp -R "$RUN/report/figures" "$DEST/figures"
cp "$RUN/report/tail.json" "$RUN/manifest.tail.json" "$RUN/checks.json" "$RUN/selection.json" "$DEST/"
[ -d "$RUN/timing" ] && cp -R "$RUN/timing" "$DEST/timing"
{
  echo "<!-- generated by scripts/publish_lm_tail.sh from $RUN; edit answer.md, not this file -->"
  [ -f "$DEST/answer.md" ] && { cat "$DEST/answer.md"; echo; }
  cat "$RUN/report/report.md"
} > "$DEST/report.md"
echo "wrote $DEST"
